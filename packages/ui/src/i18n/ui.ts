export type TranslationKey = keyof typeof ui['en'];

export function useTranslations(
	lang: SupportedLanguage = defaultLang,
	overrides?: Partial<Record<TranslationKey, string>> | Record<string, string>
) {
	return function t(key: TranslationKey | string, params?: Record<string, string | number>): string {
		if (overrides && (overrides as any)[key]) {
			let text = (overrides as any)[key];
			if (params) {
				Object.entries(params).forEach(([k, v]) => {
					text = text.replace(`{${k}}`, String(v));
				});
			}
			return text;
		}
		const langDict = ui[lang] || ui[defaultLang];
		let text: string = (langDict as any)[key] || (ui[defaultLang] as any)[key] || key;
		if (params) {
			Object.entries(params).forEach(([k, v]) => {
				text = text.replace(`{${k}}`, String(v));
			});
		}
		return text;
	};
}

export function getLocalizedPath(pathname: string, targetLocale: SupportedLanguage): string {
	let cleanPath = pathname;
	if (cleanPath.startsWith('/ko/')) {
		cleanPath = cleanPath.slice(3); // keeps leading '/'
	} else if (cleanPath === '/ko') {
		cleanPath = '/';
	} else if (cleanPath.startsWith('/zh/')) {
		cleanPath = cleanPath.slice(3); // keeps leading '/'
	} else if (cleanPath === '/zh') {
		cleanPath = '/';
	}

	if (targetLocale === 'ko') {
		if (cleanPath === '/') return '/ko';
		return `/ko${cleanPath}`;
	}
	if (targetLocale === 'zh') {
		if (cleanPath === '/') return '/zh';
		return `/zh${cleanPath}`;
	}

	return cleanPath || '/';
}

export function formatDate(date: Date, lang: SupportedLanguage = defaultLang): string {
	if (lang === 'ko') {
		return date.toLocaleDateString('ko-KR', {
			year: 'numeric',
			month: 'long',
			day: 'numeric',
			timeZone: 'UTC',
		});
	}
	if (lang === 'zh') {
		return date.toLocaleDateString('zh-CN', {
			year: 'numeric',
			month: 'long',
			day: 'numeric',
			timeZone: 'UTC',
		});
	}
	return date.toLocaleDateString('en-US', {
		year: 'numeric',
		month: 'short',
		day: 'numeric',
		timeZone: 'UTC',
	});
}
